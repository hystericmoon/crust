/** Writes the per-device width rules (F029) into packages/blocks/src/styles.css. */
import { readFile, writeFile } from "node:fs/promises";
import { responsiveCss } from "../packages/blocks/src/responsive";

const file = "packages/blocks/src/styles.css";
const START = "/* responsive:start (generated by npm run gen:responsive-css; do not edit) */";
const END = "/* responsive:end */";
const css = await readFile(file, "utf8");
const block = `${START}\n${responsiveCss()}\n${END}`;
const next = css.includes(START) ? css.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`), block) : `${css.trimEnd()}\n\n${block}\n`;
await writeFile(file, next);
console.log("styles.css: responsive rules written");
